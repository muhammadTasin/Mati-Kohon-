import assert from 'node:assert/strict';
import { RotationEngine, type PlanOptionsRequest } from './packages/rotation-engine/src/engine.ts';
import { FeatureRegistry } from './packages/rotation-engine/src/registry.ts';

const request: PlanOptionsRequest = { unionId: 'ADM3_Shyamnagar', unionNameBangla: 'শ্যামনগর', upazila: 'Shyamnagar', district: 'Satkhira', landType: 'medium_high', season: '2026-aman', today: '2026-11-05', farmerPriorities: { water: .5, income: .3, soil: .2 }, currentRotation: { monsoon: 'aman', winter: 'fallow' } };
const engine = new RotationEngine();
const advice = engine.generateAdvice(request);
const reference = advice.current_practice_reference!;
assert.ok(reference);
assert.equal(reference.kind, 'unranked_fallow_reference');
assert.equal(reference.irrigationExcludingAmanMm, 0);
assert.equal(reference.winterCropNetReturnBdtPerHa, 0);
assert.equal(reference.amanVariety, 'BRRI dhan49');
assert.equal(reference.amanVarietyAssumed, true);
assert.equal('scores' in reference, false, 'No fabricated score for fallow');
assert.equal(advice.reference_option_id, null, 'Do not silently substitute Boro');
assert.ok(advice.options.every(o => o.review?.referenceId === reference.id));
assert.ok(!advice.options.some(o => o.id === reference.id), 'An unranked reference must not become the recommendation');
assert.equal(reference.comparisons.length, advice.options.length);
for (const option of advice.options) {
  const comparison = reference.comparisons.find(c => c.optionId === option.id)!;
  assert.equal(comparison.illustrativeNetReturnChangeBdtPerHa, Number(option.dimensionDetails.income.metrics.illustrativeTotalBdtPerHa) - reference.illustrativeAnnualNetReturnBdtPerHa);
  assert.ok(comparison.addedIrrigationExcludingAmanMm! >= 0, 'Adding an irrigated crop cannot save water against no crop');
  assert.ok(!option.review!.benefits.some(l => /lower modeled irrigation demand|less groundwater pumped/.test(l.en)));
  assert.ok(option.review!.benefits.some(l => l.en.includes('excluding Aman')));
}
const ordinary = engine.generateAdvice({ ...request, currentRotation: undefined });
assert.deepEqual(advice.options.map(o => [o.id, o.scores]), ordinary.options.map(o => [o.id, o.scores]), 'Reference must not alter candidate scoring');
assert.equal(ordinary.current_practice_reference, null, 'Absent and explicitly fallow are distinct');
const pilotFallow = engine.generateAdvice({ ...request, unionId: 'talanda_tanore', currentAmanCrop: 'BRRI dhan49' });
assert.ok(pilotFallow.current_practice_reference);
assert.ok(pilotFallow.options.every(o => !o.farmerCurrent && !o.nameEnglish.includes('current practice')), 'A Boro comparator must not be labelled as the farmer\'s practice when they supplied fallow');
const known = engine.generateAdvice({ ...request, currentAmanCrop: 'BRRI dhan71' }).current_practice_reference!;
assert.equal(known.amanVariety, 'BRRI dhan71');
assert.equal(known.amanVarietyAssumed, false);
const allFallow = engine.generateAdvice({ ...request, currentRotation: { monsoon: 'fallow', winter: 'fallow' } }).current_practice_reference!;
assert.equal(allFallow.illustrativeAnnualNetReturnBdtPerHa, 0);
assert.equal(allFallow.amanRescueSeasons, null);
const summer = engine.generateAdvice({ ...request, currentRotation: { monsoon: 'aman', winter: 'fallow', summer: 'jute' } });
assert.equal(summer.current_practice_reference, null, 'Never silently drop a supplied summer crop');
assert.ok(summer.current_rotation_note);
const flooded = engine.generateAdvice({ ...request, unionId: 'ADM3_Khaliajuri', landType: 'low' });
assert.equal(flooded.current_practice_reference, null, 'Do not put Aman on land where the rules exclude it');
const registry = new FeatureRegistry();
registry.setFeatureFlag('water', false);
registry.setFeatureFlag('income', false);
const limited = new RotationEngine(registry).generateAdvice(request);
assert.ok(limited.current_practice_reference!.comparisons.every(c => c.addedIrrigationExcludingAmanMm === null && c.illustrativeNetReturnChangeBdtPerHa === null), 'Disabled evidence produces unknown differences, not zero');
console.log('Current-practice checks passed: fallow quantities, signed trade-offs, assumed varieties, land limits, missing evidence and unchanged ranking.');
